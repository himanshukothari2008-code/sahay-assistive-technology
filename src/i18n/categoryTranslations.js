/**
 * Returns a localized category object with translated titles, summaries, content blocks, and quizzes.
 */
export function getLocalizedCategory(cat, lang = 'en') {
  if (!cat) return null;
  const currentLang = (lang || 'en').split('-')[0];
  if (currentLang === 'en') return cat;

  const meta = categoryMetaTranslations[cat.slug]?.[currentLang];
  const blocksMeta = categoryBlockTranslations[cat.slug]?.[currentLang];

  const localizedCat = {
    ...cat,
    title: meta?.title || cat.title,
    summary: meta?.summary || cat.summary
  };

  // Localize content blocks
  if (cat.blocks && Array.isArray(cat.blocks) && blocksMeta) {
    localizedCat.blocks = cat.blocks.map((block) => {
      let transBlock = null;
      if (block.type === 'overview') {
        transBlock = blocksMeta.overview;
      } else if (block.type === 'myth_fact') {
        transBlock = blocksMeta.myth_fact || blocksMeta.overview?.mythFact || blocksMeta.mythFact;
      } else if (block.type === 'challenge') {
        transBlock = blocksMeta.challenge || blocksMeta.challenges;
      } else if (block.type === 'simulation') {
        transBlock = blocksMeta.simulation || blocksMeta.simulations;
      } else if (block.type === 'solution') {
        transBlock = blocksMeta.solution || blocksMeta.solutions;
      } else if (block.type === 'tool') {
        transBlock = blocksMeta.tool || blocksMeta.tools;
      } else if (block.type === 'resource') {
        transBlock = blocksMeta.resource || blocksMeta.resources;
      }

      if (!transBlock) return block;

      const updated = { ...block };
      if (typeof transBlock === 'string') {
        updated.body_markdown = transBlock;
      } else {
        if (transBlock.title) updated.title = transBlock.title;
        if (transBlock.body) updated.body_markdown = transBlock.body;
        if (transBlock.easyRead) updated.easy_read_body = transBlock.easyRead;
      }
      return updated;
    });
  }

  // Localize media gallery items if present
  if (cat.media && Array.isArray(cat.media)) {
    localizedCat.media = cat.media.map((m) => {
      const transM = mediaTranslations[m.id]?.[currentLang];
      if (!transM) return m;

      return {
        ...m,
        title: transM.title || m.title,
        caption: transM.caption || m.caption,
        transcript: transM.transcript || m.transcript
      };
    });
  }

  // Localize quiz questions if present
  if (cat.quiz && Array.isArray(cat.quiz)) {
    localizedCat.quiz = cat.quiz.map((q) => {
      const transQ = quizQuestionTranslations[q.id]?.[currentLang];
      if (!transQ) return q;

      return {
        ...q,
        question: transQ.question || q.question,
        options: transQ.options || q.options,
        explanation: transQ.explanation || q.explanation
      };
    });
  }

  return localizedCat;
}

/**
 * Returns a localized array of categories for the homepage list.
 */
export function getLocalizedCategoryList(categories, lang = 'en') {
  if (!categories || !Array.isArray(categories)) return [];
  const currentLang = (lang || 'en').split('-')[0];
  if (currentLang === 'en') return categories;

  return categories.map((cat) => {
    const meta = categoryMetaTranslations[cat.slug]?.[currentLang];
    return {
      ...cat,
      title: meta?.title || cat.title,
      summary: meta?.summary || cat.summary
    };
  });
}

